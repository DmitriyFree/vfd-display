#pragma once
#include <Arduino.h>

// Segment bits: a=0x01 b=0x02 c=0x04 d=0x08 e=0x10 f=0x20 g=0x40 dp=0x80
// ASCII 32..126. Table taken from the old firmware; fixed 'C' and '(' (they were copies of 'E').
static const uint8_t FONT[95] = {
  // 32-39:  ' '   !     "     #     $     %     &     '
  0x00, 0x82, 0x01, 0x63, 0x11, 0x63, 0x04, 0x02,
  // 40-47:  (     )     *     +     ,     -     .     /
  0x39, 0x0F, 0x20, 0x46, 0x80, 0x40, 0x80, 0x52,
  // 48-57:  0-9
  0x3F, 0x06, 0x5B, 0x4F, 0x66, 0x6D, 0x7D, 0x07, 0x7F, 0x6F,
  // 58-64:  :     ;     <     =     >     ?     @
  0x48, 0x48, 0x58, 0x48, 0x4C, 0x83, 0x5F,
  // 65-90:  A-Z
  0x77, 0x7C, 0x39, 0x5E, 0x79, 0x71, 0x3D, 0x76, 0x06, 0x1F, 0x68, 0x38, 0x15,
  0x54, 0x3F, 0x73, 0x67, 0x50, 0x6D, 0x78, 0x3E, 0x3E, 0x2A, 0x76, 0x6E, 0x1B,
  // 91-96:  [     \     ]     ^     _     `
  0x39, 0x24, 0x0F, 0x23, 0x08, 0x20,
  // 97-122: a-z
  0x77, 0x7C, 0x58, 0x5E, 0x79, 0x71, 0x3D, 0x74, 0x06, 0x1E, 0x68, 0x38, 0x15,
  0x54, 0x5C, 0x73, 0x67, 0x50, 0x6D, 0x78, 0x1C, 0x1C, 0x2A, 0x76, 0x6E, 0x1B,
  // 123-126: {    |     }     ~
  0x09, 0x30, 0x09, 0x40
};

inline uint8_t glyph(char c) {
  uint8_t u = (uint8_t)c;
  if (u < 32 || u > 126) return 0;
  return FONT[u - 32];
}
